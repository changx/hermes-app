import assert from 'node:assert/strict';
import { HermesClient, HttpError } from '../../packages/client/dist/index.js';
import { nativeTransport } from '../../apps/mobile/src/transport.ts';
const [base,cid]=process.argv.slice(2);
const token='synthetic-workspace-interop-token-at-least-32-characters';
const transport=nativeTransport(base), client=new HermesClient({...transport,token:()=>token});
await client.capabilities();assert.equal(client.supportsChannelWorkspace,true);
assert.equal((await client.workspace.getState(cid)).initialized,false);
await client.workspace.initialize(cid);
await assert.rejects(client.workspace.getAgents(cid),e=>e instanceof HttpError&&e.status===404);
const content='\n# Channel guidelines\n保留完整原文 🌍\n ';
const made=await client.workspace.saveAgents(cid,content,null);
assert.equal(made.content,content);
assert.equal(new TextDecoder().decode(await client.workspace.readFile(cid,'AGENTS.md')),content);
const second=new HermesClient({...transport,token:()=>token});
const changed=await second.workspace.saveAgents(cid,'Other device rules',made.etag);
await assert.rejects(client.workspace.saveAgents(cid,'Must not overwrite',made.etag),e=>e instanceof HttpError&&e.status===412);
assert.equal((await client.workspace.getAgents(cid)).content,'Other device rules');
await client.workspace.saveAgents(cid,'',changed.etag);assert.equal((await second.workspace.getAgents(cid)).content,'');
await client.workspace.mkdir(cid,'docs');
const fileResponse=await fetch(base+'/v1/channels/'+cid+'/file?path=docs%2Fnote.md',{method:'PUT',headers:{Authorization:'Bearer '+token,'If-None-Match':'*','Content-Type':'application/octet-stream'},body:'# Real reference file\n'});
assert.equal(fileResponse.status,200);
const listing=await client.workspace.list(cid);assert.deepEqual(listing.items.map(x=>x.name),['AGENTS.md','docs']);
assert.equal((await client.workspace.list(cid,'docs')).items[0].path,'docs/note.md');
assert.equal(new TextDecoder().decode(await client.workspace.readFile(cid,'docs/note.md')),'# Real reference file\n');
const inventory=await client.workspace.attachments(cid);assert.equal(inventory.items[0].state,'available');
assert.equal(new TextDecoder().decode(await client.download(inventory.items[0].thread_id,inventory.items[0].id)),'Attachment reference');
assert.equal(client.messages.size,0);assert.equal(client.attachments.size,0);
console.log(JSON.stringify({real_plugin_http:true,native_transport:true,conditional_create_replace_clear:true,original_version_conflict:true,exact_file_readback:true,directory_and_attachment_inventory:true,no_chat_body_cache:true}));
